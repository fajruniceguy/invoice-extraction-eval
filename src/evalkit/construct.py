"""Constructed invoices: synthetic documents whose ground truth is known by construction.

Real long, multi-page invoices are rare in a small dataset, and a table that continues over pages
(with the totals only on the last page) is exactly where extraction breaks. So three invoices are
generated in three different layouts, each with 30-60 rupiah line items over 2 or 3 pages. The
subtotal, discount, PPN and total are printed on the LAST page only, and one layout repeats a
"(lanjutan)" header on every continuation page.

Everything printed is generated from one `Invoice` value, and the ground truth is derived from
that same value as the document PRINTS it (never recomputed from what an extractor might read):
money in Indonesian format ("1.250.000,00") becomes a decimal string ("1250000.00") at the
printed scale, dates become ISO dates, and a field the layout does not print is explicit `null`.

Deterministic: the content depends only on (seed, doc_id, layout), and the PDFs carry no dates or
random ids (reportlab `invariant`), so the same inputs give byte-identical files. The PDFs are
written under data/private/raw/constructed/ (gitignored, regenerated by the script).

reportlab is a dev dependency and is imported lazily.
"""

