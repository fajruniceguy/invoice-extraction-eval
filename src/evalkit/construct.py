@dataclass(frozen=True)
class Invoice:
    doc_id: str
    layout: str
    vendor_name: str
    vendor_address: str
    vendor_tax_id: str
    buyer_name: str
    number: str
    issued: date
    due: date | None
    items: tuple[Item, ...]
    subtotal: Decimal
    discount: Decimal | None
    tax: Decimal
    total: Decimal


# ---------------------------------------------------------------- formatting


def format_money(value: Decimal, decimals: bool) -> str:
    """Indonesian number format: '.' groups thousands, ',' marks decimals."""
    q = value.quantize(Decimal("0.01") if decimals else Decimal(1), rounding=ROUND_HALF_UP)
    whole, _, fraction = f"{abs(q):f}".partition(".")
    grouped = f"{int(whole):,}".replace(",", ".")
    sign = "-" if q < 0 else ""
    return f"{sign}{grouped},{fraction}" if decimals else f"{sign}{grouped}"


def format_quantity(value: Decimal) -> str:
    return str(int(value)) if value == value.to_integral_value() else f"{value:f}".replace(".", ",")


def format_date(value: date, style: str) -> str:
    if style == "long":
        return f"{value.day} {MONTHS[value.month - 1]} {value.year}"
    if style == "slash":
        return f"{value.day:02d}/{value.month:02d}/{value.year}"
    return value.isoformat()


def gt_money(value: Decimal, decimals: bool) -> str:
    """The ground-truth string of a printed amount: a decimal string at the PRINTED scale."""
    return (
        f"{value.quantize(Decimal('0.01') if decimals else Decimal(1), rounding=ROUND_HALF_UP):f}"
    )


# ---------------------------------------------------------------- generation


def _whole(value: Decimal) -> Decimal:
    return value.quantize(Decimal(1), rounding=ROUND_HALF_UP)


def generate_invoice(doc_id: str, layout_name: str, seed: str = DEFAULT_SEED) -> Invoice:
    layout = LAYOUTS[layout_name]
    rng = random.Random(f"{seed}|{doc_id}|{layout_name}")
    count = rng.randint(*layout.items)
    items: list[Item] = []
    for description in rng.sample(ITEM_NAMES, count):
        quantity = Decimal(rng.randint(1, 40))
        if layout.fractional_quantities and rng.random() < 0.25:
            quantity = Decimal(rng.randint(1, 20)) + Decimal("0.5")
        unit_price = Decimal(500 * rng.randint(2, 4000))  # 1.000 .. 2.000.000
        items.append(Item(description, quantity, unit_price, quantity * unit_price))
    subtotal = sum((item.amount for item in items), Decimal(0))
    discount: Decimal | None = None
    if layout.discount == "percent":
        discount = _whole(subtotal * Decimal("0.05"))
    elif layout.discount == "fixed":
        discount = Decimal(1000 * rng.randint(50, 500))
    taxable = subtotal - (discount or Decimal(0))
    tax = _whole(taxable * Decimal("0.11"))
    vendor_name, vendor_address = rng.choice(VENDORS)
    issued = date(2024, 1, 1) + timedelta(days=rng.randint(0, 330))
    tax_id = (
        f"{rng.randint(10, 99)}.{rng.randint(100, 999)}.{rng.randint(100, 999)}."
        f"{rng.randint(0, 9)}-{rng.randint(100, 999)}.000"
    )
    return Invoice(
        doc_id=doc_id,
        layout=layout_name,
        vendor_name=vendor_name,
        vendor_address=vendor_address,
        vendor_tax_id=tax_id,
        buyer_name=rng.choice(BUYERS),
        number=layout.number_format.format(year=issued.year, serial=rng.randint(1, 9999)),
        issued=issued,
        due=issued + timedelta(days=30) if layout.prints_due_date else None,
        items=tuple(items),
        subtotal=subtotal,
        discount=discount,
        tax=tax,
        total=taxable + tax,
    )


# ---------------------------------------------------------------- pagination


def row_capacities(layout: Layout) -> tuple[int, int, int]:
    """Rows that fit on the first page, a middle page and the last page (which also holds the
    totals block)."""
    first = int((layout.first_table_top - layout.row_height - BOTTOM) // layout.row_height)
    middle = int((layout.cont_table_top - layout.row_height - BOTTOM) // layout.row_height)
    last = middle - math.ceil(layout.totals_height / layout.row_height)
    return first, middle, last


def paginate(count: int, first: int, middle: int, last: int) -> list[int]:
    """Rows per page: at least two pages, rows fill pages in order, and the last page holds at
    least MIN_LAST_PAGE_ROWS rows besides the totals."""
    pages = 2
    while first + (pages - 2) * middle + last < count:
        pages += 1
    caps = [first, *([middle] * (pages - 2)), last]
    sizes: list[int] = []
    remaining = count
    for cap in caps[:-1]:
        take = min(cap, remaining)
        sizes.append(take)
        remaining -= take
    sizes.append(remaining)
    deficit = MIN_LAST_PAGE_ROWS - sizes[-1]
    for index in range(len(sizes) - 2, -1, -1):  # borrow from the pages before it
        if deficit <= 0:
            break
        give = min(deficit, sizes[index] - MIN_LAST_PAGE_ROWS)
        sizes[index] -= give
        sizes[-1] += give
        deficit -= give
    if not MIN_LAST_PAGE_ROWS <= sizes[-1] <= last or sum(sizes) != count:
        raise ValueError(f"cannot paginate {count} rows into {caps}")
    return sizes


def page_plan(invoice: Invoice) -> list[int]:
    return paginate(len(invoice.items), *row_capacities(LAYOUTS[invoice.layout]))


# ---------------------------------------------------------------- rendering


def _cell_text(invoice: Invoice, layout: Layout, column: Column, index: int, item: Item) -> str:
    if column.key == "no":
        return str(index)
    if column.key == "code":
        return f"BRG-{index:03d}"
    if column.key == "desc":
        return item.description
    if column.key == "qty":
        return format_quantity(item.quantity)
    value = item.unit_price if column.key == "unit_price" else item.amount
    return format_money(value, layout.money_decimals)


def render_invoice(invoice: Invoice, path: Path) -> list[int]:
    """Write the PDF and return the number of rows on each page."""
    from reportlab.pdfbase.pdfmetrics import stringWidth
    from reportlab.pdfgen import canvas

    layout = LAYOUTS[invoice.layout]
    plan = page_plan(invoice)
    path.parent.mkdir(parents=True, exist_ok=True)
    pdf = canvas.Canvas(str(path), pagesize=(PAGE_W, PAGE_H), invariant=1, pageCompression=0)
    pdf.setTitle(invoice.doc_id)
    right = PAGE_W - MARGIN
    accent = layout.accent

    def text(x: float, y: float, value: str, bold: bool = False, size: float | None = None) -> None:
        pdf.setFont(layout.bold if bold else layout.font, size or layout.size)
        pdf.drawString(x, y, value)

    def text_right(x: float, y: float, value: str, bold: bool = False) -> None:
        pdf.setFont(layout.bold if bold else layout.font, layout.size)
        pdf.drawRightString(x, y, value)

    def first_page_header() -> None:
        issued = format_date(invoice.issued, layout.date_style)
        meta = [("No.", invoice.number), ("Tanggal", issued)]
        if invoice.due is not None:
            meta.append(("Jatuh Tempo", format_date(invoice.due, layout.date_style)))
        if layout.prints_payment_method:
            meta.append(("Pembayaran", layout.payment_method))
        if layout.name == "classic":
            text(MARGIN, 800, layout.title, bold=True, size=16)
            text(MARGIN, 776, invoice.vendor_name, bold=True, size=11)
            text(MARGIN, 762, invoice.vendor_address)
            text(MARGIN, 748, f"NPWP: {invoice.vendor_tax_id}")
            for line, (label, value) in enumerate(meta):
                text(330, 776 - line * 14, f"{label}")
                text(410, 776 - line * 14, f": {value}")
            text(MARGIN, 700, "Kepada Yth:", bold=True)
            text(MARGIN, 686, invoice.buyer_name)
        elif layout.name == "modern":
            pdf.setFillColorRGB(*accent)
            pdf.rect(0, PAGE_H - 90, PAGE_W, 90, stroke=0, fill=1)
            pdf.setFillColorRGB(1, 1, 1)
            text(MARGIN, PAGE_H - 45, layout.title, bold=True, size=24)
            text(300, PAGE_H - 38, invoice.vendor_name, bold=True, size=12)
            text(300, PAGE_H - 54, invoice.vendor_address, size=9)
            pdf.setFillColorRGB(0, 0, 0)
            for line, (label, value) in enumerate(meta):
                text(MARGIN, 700 - line * 16, f"{label} Invoice" if label == "No." else label)
                text(150, 700 - line * 16, value, bold=True)
            text(330, 700, "Ditagihkan kepada", bold=True)
            text(330, 684, invoice.buyer_name)
        else:
            pdf.setLineWidth(0.8)
            pdf.rect(MARGIN, 735, right - MARGIN, 85, stroke=1, fill=0)
            text(MARGIN + 8, 802, layout.title, bold=True, size=12)
            text(MARGIN + 8, 786, invoice.vendor_name, bold=True)
            text(MARGIN + 8, 773, invoice.vendor_address)
            text(MARGIN + 8, 760, f"NPWP {invoice.vendor_tax_id}")
            for line, (label, value) in enumerate(meta):
                text(MARGIN, 715 - line * 13, f"{label:<12}: {value}")
            text(330, 715, "Pembeli:", bold=True)
            text(330, 702, invoice.buyer_name)

    def table_header(top: float) -> None:
        x = MARGIN
        if layout.name == "modern":
            pdf.setFillColorRGB(*accent)
            pdf.rect(MARGIN, top - 6, right - MARGIN, layout.row_height, stroke=0, fill=1)
            pdf.setFillColorRGB(1, 1, 1)
        elif layout.name == "classic":
            pdf.setFillColorRGB(0.85, 0.85, 0.85)
            pdf.rect(MARGIN, top - 5, right - MARGIN, layout.row_height, stroke=1, fill=1)
            pdf.setFillColorRGB(0, 0, 0)
        else:
            pdf.line(MARGIN, top + 12, right, top + 12)
            pdf.line(MARGIN, top - 6, right, top - 6)
        for column in layout.columns:
            if column.align == "left":
                text(x + 3, top, column.header, bold=True)
            else:
                text_right(x + column.width - 3, top, column.header, bold=True)
            x += column.width
        pdf.setFillColorRGB(0, 0, 0)

    def table_row(y: float, index: int, item: Item) -> None:
        x = MARGIN
        if layout.name == "classic":
            pdf.setLineWidth(0.4)
            pdf.rect(MARGIN, y - 5, right - MARGIN, layout.row_height, stroke=1, fill=0)
        elif layout.name == "modern" and index % 2 == 0:
            pdf.setFillColorRGB(0.93, 0.95, 0.98)
            pdf.rect(MARGIN, y - 6, right - MARGIN, layout.row_height, stroke=0, fill=1)
            pdf.setFillColorRGB(0, 0, 0)
        elif layout.name == "compact":
            pdf.setDash(1, 2)
            pdf.line(MARGIN, y - 6, right, y - 6)
            pdf.setDash()
        for column in layout.columns:
            cell = _cell_text(invoice, layout, column, index, item)
            if (
                column.key == "desc"
                and stringWidth(cell, layout.font, layout.size) > column.width - 8
            ):
                raise ValueError(f"{invoice.doc_id}: {cell!r} does not fit its column")
            if column.align == "left":
                text(x + 3, y, cell)
            else:
                text_right(x + column.width - 3, y, cell)
            x += column.width

    def totals(y: float) -> None:
        lines = [(layout.labels["subtotal"], invoice.subtotal)]
        if invoice.discount is not None:
            lines.append((layout.labels["discount"], invoice.discount))
        lines.append((layout.labels["tax"], invoice.tax))
        lines.append((layout.labels["total"], invoice.total))
        label_x = right - 250 if layout.name != "compact" else MARGIN + 6
        for line, (label, value) in enumerate(lines):
            last = line == len(lines) - 1
            line_y = y - line * 18
            money = f"{layout.money_prefix}{format_money(value, layout.money_decimals)}"
            if last:
                pdf.setLineWidth(1)
                pdf.line(
                    label_x,
                    line_y + 13,
                    right if layout.name != "compact" else MARGIN + 300,
                    line_y + 13,
                )
            text(label_x, line_y, label, bold=last)
            value_right = right if layout.name != "compact" else MARGIN + 300
            text_right(value_right, line_y, money, bold=last)

    total_pages = len(plan)
    cursor = 0
    for number, rows in enumerate(plan, start=1):
        if number == 1:
            first_page_header()
            top = layout.first_table_top
        else:
            top = layout.cont_table_top
            if layout.continued_header:
                pdf.setFillColorRGB(*accent)
                pdf.rect(0, PAGE_H - 50, PAGE_W, 50, stroke=0, fill=1)
                pdf.setFillColorRGB(1, 1, 1)
                text(
                    MARGIN,
                    PAGE_H - 30,
                    f"(lanjutan) Invoice No. {invoice.number}",
                    bold=True,
                    size=12,
                )
                pdf.setFillColorRGB(0, 0, 0)
            else:
                text(MARGIN, PAGE_H - 30, f"{layout.title}  {invoice.number}", bold=True)
        table_header(top)
        y = top - layout.row_height
        for _ in range(rows):
            cursor += 1
            table_row(y, cursor, invoice.items[cursor - 1])
            y -= layout.row_height
        if number == total_pages:
            totals(y - 14)
        text(PAGE_W / 2 - 40, 28, f"Halaman {number} dari {total_pages}", size=8)
        pdf.showPage()
    pdf.save()
    return plan


# ---------------------------------------------------------------- ground truth and manifest


def ground_truth(invoice: Invoice) -> dict[str, Any]:
    """The label as the document PRINTS it. A field the layout does not print is null (absent)."""
    layout = LAYOUTS[invoice.layout]
    plan = page_plan(invoice)
    decimals = layout.money_decimals
    notes = [
        f"constructed ({layout.name} layout): {len(invoice.items)} line items over "
        f"{len(plan)} pages",
        "subtotal, discount, tax and total are printed on the last page only",
    ]
    if layout.continued_header:
        notes.append("continuation pages repeat a '(lanjutan)' header")
    absent = [
        name
        for name, printed in (
            ("due_date", layout.prints_due_date),
            ("vendor_tax_id", layout.prints_tax_id),
            ("payment_method", layout.prints_payment_method),
            ("discount", layout.discount is not None),
        )
        if not printed
    ]
    if absent:
        notes.append("not printed: " + ", ".join(absent))
    return {
        "doc_id": invoice.doc_id,
        "notes": "; ".join(notes),
        "vendor_name": invoice.vendor_name,
        "vendor_address": invoice.vendor_address,
        "vendor_tax_id": invoice.vendor_tax_id if layout.prints_tax_id else None,
        "buyer_name": invoice.buyer_name,
        "document_number": invoice.number,
        "document_date": invoice.issued.isoformat(),
        "due_date": invoice.due.isoformat() if invoice.due is not None else None,
        "currency": "IDR",
        "payment_method": layout.payment_method if layout.prints_payment_method else None,
        "line_items": [
            {
                "description": item.description,
                "quantity": f"{item.quantity:f}",
                "unit_price": gt_money(item.unit_price, decimals),
                "amount": gt_money(item.amount, decimals),
            }
            for item in invoice.items
        ],
        "subtotal": gt_money(invoice.subtotal, decimals),
        "tax": gt_money(invoice.tax, decimals),
        "discount": gt_money(invoice.discount, decimals) if invoice.discount is not None else None,
        "total": gt_money(invoice.total, decimals),
    }


